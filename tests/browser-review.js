// Run with Playwright CLI run-code --filename tests/browser-review.js against a local preview.
async (page) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(6000)
  const check = (value, message) => { if (!value) throw new Error(message) }
  const settle = () => page.waitForTimeout(800)
  const canvas = page.locator('canvas')
  const picture = () => canvas.screenshot()
  const focus = () => page.locator('.plant-detail h3').innerText()
  const reset = async () => { await page.getByRole('button', { name: 'Centrar todo' }).click(); await settle() }
  await page.setViewportSize({ width: 1366, height: 768 })
  await page.reload({ waitUntil:'domcontentloaded' })
  await page.getByRole('heading', { name: 'Observa y compara', exact: true }).waitFor()
  check(await page.locator('.scene-failure').count() === 0, 'WebGL no inició')

  for (const [width, height] of [[1280, 600], [1100, 650], [1366, 650], [1366, 768], [1440, 900], [1024, 768]]) {
    await page.setViewportSize({ width, height })
    await page.evaluate(() => scrollTo(0, 0))
    const timeline = await page.locator('.timeline').boundingBox()
    await page.locator('.sample-note').scrollIntoViewIfNeeded()
    const comparison = await page.locator('.sample-note').boundingBox()
    const panel = await page.locator('.data-panel').boundingBox()
    const legend = await page.locator('.chart-footer').boundingBox()
    const graph = await page.locator('.temporal-chart svg').boundingBox()
    check(timeline.y + timeline.height <= height, 'Línea temporal fuera del escritorio ' + width)
    check(comparison.y + comparison.height <= panel.y + panel.height, 'La muestra no es accesible dentro del panel ' + width)
    check(graph.y + graph.height <= legend.y + 1, 'La gráfica invade la leyenda ' + width)
    check(legend.y + legend.height <= comparison.y + 1, 'La leyenda invade la nota de muestra ' + width)
    check(await page.locator('.data-panel').evaluate(el => ['auto', 'scroll'].includes(getComputedStyle(el).overflowY)), 'El panel no contiene el desbordamiento')
  }
  await page.setViewportSize({ width: 1366, height: 768 })
  await reset()
  const beforeZoom = await picture()
  const box = await canvas.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.wheel(0, -400)
  await page.waitForTimeout(150)
  const zoomed = await picture()
  check(!beforeZoom.equals(zoomed), 'La rueda no cambia el zoom')
  await settle()
  check(zoomed.equals(await picture()), 'El ajuste automático está anulando el zoom')
  check((await page.locator('.camera-status').innerText()).includes('libre'), 'No se indica exploración libre')
  const selected = await focus()
  await page.mouse.move(box.x + box.width * 0.35, box.y + box.height * 0.55)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.55, box.y + box.height * 0.62, { steps: 8 })
  await page.mouse.move(box.x + box.width * 0.35, box.y + box.height * 0.55, { steps: 8 })
  await page.mouse.up()
  check(await focus() === selected, 'Arrastrar y regresar al origen selecciona una parcela')
  await settle()
  const beforePan = await picture()
  await page.mouse.down({ button: 'right' })
  await page.mouse.move(box.x + box.width * 0.5, box.y + box.height * 0.5, { steps: 8 })
  await page.mouse.up({ button: 'right' })
  await settle()
  check(!(await picture()).equals(beforePan), 'El arrastre derecho no desplaza')
  check(await focus() === selected, 'Desplazar selecciona una parcela')
  await page.getByRole('button', { name: 'Superior', exact: true }).click()
  await settle()
  await page.locator('.field-wrap').screenshot({ path: 'output/playwright/review-top.png' })
  check((await page.locator('.camera-status').innerText()).includes('ocultas'), 'No se ocultan las cubiertas')
  await page.mouse.click(box.x + box.width * 0.19, box.y + box.height * 0.5)
  check(await focus() === 'Sarán rojo', 'El clic simple no selecciona la parcela roja')
  check(await page.getByRole('button', { name: 'Superior', exact: true }).getAttribute('aria-pressed') === 'true', 'Un clic simple cambia la cámara')
  await page.mouse.move(box.x + box.width * 0.45, box.y + box.height * 0.5)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.57, box.y + box.height * 0.6, { steps: 8 })
  await page.mouse.up()
  check((await page.locator('.camera-status').innerText()).includes('libre'), 'Rotar no devuelve las cubiertas')
  await reset()
  await page.getByRole('button', { name: 'Acercar escenario' }).click({ clickCount: 24 })
  const maxZoom = await picture()
  await page.getByRole('button', { name: 'Acercar escenario' }).click({ clickCount: 3 })
  check(maxZoom.equals(await picture()), 'Falta límite superior de zoom')
  await page.getByRole('button', { name: 'Alejar escenario' }).click({ clickCount: 26 })
  const minZoom = await picture()
  await page.getByRole('button', { name: 'Alejar escenario' }).click({ clickCount: 3 })
  check(minZoom.equals(await picture()), 'Falta límite inferior de zoom')
  await reset()
  await page.getByRole('button', { name: 'Lateral', exact: true }).click()
  await settle()
  await page.locator('.field-wrap').screenshot({ path: 'output/playwright/review-side.png' })
  await page.locator('.field-canvas').focus()
  await page.keyboard.press('+')
  check((await page.locator('.camera-status').innerText()).includes('libre'), 'Zoom por teclado no responde')
  await page.keyboard.press('r')
  await settle()
  check(await page.getByRole('button', { name: 'Frontal', exact: true }).getAttribute('aria-pressed') === 'true', 'R no restablece')

  await page.getByRole('button', { name: 'Sin sarán', exact: true }).click()
  await page.getByRole('button', { name: 'Sem. 9 15 oct', exact: true }).click()
  check((await page.locator('.plant-detail').innerText()).includes('8 muestras con datos'), 'Se alteró n de semana 9')
  await page.getByRole('button', { name: 'Sem. 10 22 oct', exact: true }).click()
  check((await page.locator('.plant-detail').innerText()).includes('5 muestras con datos'), 'Se alteró n de semana 10')
  await page.getByRole('combobox', { name: 'Variable biométrica' }).selectOption('flowers')
  check((await page.locator('.comparison').innerText()).includes('1.75'), 'Se perdió la comparación de flores')
  await page.getByRole('button', { name: 'Sem. 1 20 ago', exact: true }).click()
  check((await page.locator('.comparison').innerText()).includes('Sin datos'), 'Los ausentes se convirtieron en ceros')
  check(await page.locator('.chart-point').count() === 16, 'Se inventaron puntos de flores en semanas sin mediciones')
  check(await page.locator('.chart-point[tabindex="0"]').count() === 1, 'No se puede entrar al gráfico por teclado con la semana actual sin datos')
  check((await page.locator('.sample-note').innerText()).includes('0 mediciones'), 'n incorrecto para flores ausentes')
  await page.locator('.week-buttons button').nth(11).click()
  check((await page.locator('.comparison').innerText()).includes('0.00'), 'Se perdieron ceros medidos')
  check((await page.locator('.detail-metrics').innerText()).includes('Altura · n=4') && (await page.locator('.detail-metrics').innerText()).includes('Diámetro del tallo · n=3'), 'Se mezclaron denominadores del control en semana 12')
  for (const name of ['Rojo', 'Azul', 'Verde', 'Control']) await page.getByRole('checkbox', { name, exact: true }).uncheck()
  check(await page.getByText('Selecciona un tratamiento para comparar sus registros.', { exact: true }).isVisible(), 'Falta estado vacío')
  await page.getByRole('button', { name: 'Sarán azul', exact: true }).click()
  check(await page.getByRole('checkbox', { name: 'Azul', exact: true }).isChecked(), 'No se recupera el tratamiento')
  for (const name of ['Rojo', 'Verde', 'Control']) await page.getByRole('checkbox', { name, exact: true }).check()
  await page.getByRole('slider').focus()
  await page.keyboard.press('End')
  check(await page.getByRole('slider').inputValue() === '13', 'El tiempo no responde al teclado')
  await page.getByRole('button', { name: 'Sarán verde', exact: true }).click()
  check((await page.locator('.detail-metrics').innerText()).includes('Altura · n=7'), 'Se perdió el dato ausente de altura verde en semana 13')
  await page.getByRole('combobox', { name: 'Variable biométrica' }).selectOption('height')
  for (const width of [768, 390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await page.evaluate(() => scrollTo(0, 0))
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Desbordamiento horizontal a ' + width)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'output/playwright/review-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 900 })
  await reset()
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: 'output/playwright/review-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Acercar escenario' }).click({ clickCount: 2 })
  await page.locator('.field-wrap').screenshot({ path: 'output/playwright/review-detail.png' })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Superior', exact: true }).click()
  await page.waitForTimeout(100)
  const reduced = await picture()
  await page.waitForTimeout(300)
  check(reduced.equals(await picture()), 'La cámara sigue animándose con movimiento reducido')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await reset()
  const mobileContext = await page.context().browser().newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
  try {
    const mobile = await mobileContext.newPage()
    mobile.on('pageerror', error => errors.push(error.message))
    await mobile.goto(page.url())
    await mobile.getByRole('heading', { name: 'Observa y compara', exact: true }).waitFor()
    await mobile.locator('.touch-help').waitFor({ state: 'visible' })
    await mobile.screenshot({ path: 'output/playwright/review-touch.png', fullPage: true })
    const touchCanvas = mobile.locator('canvas')
    const touchBox = await touchCanvas.boundingBox()
    const client = await mobileContext.newCDPSession(mobile)
    const x = touchBox.x + touchBox.width * 0.5, y = touchBox.y + touchBox.height * 0.5
    const beforeTouch = await mobile.locator('.plant-detail h3').innerText()
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y, id: 1 }] })
    await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + 55, y: y + 15, id: 1 }] })
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await mobile.getByRole('group', { name: 'Cultivo ilustrativo en vista libre', exact: true }).waitFor()
    check(await mobile.locator('.plant-detail h3').innerText() === beforeTouch, 'El arrastre táctil selecciona parcelas')
    await settle()
    const beforePinch = await touchCanvas.screenshot()
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: x - 30, y, id: 1 }, { x: x + 30, y, id: 2 }] })
    await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - 65, y: y + 10, id: 1 }, { x: x + 85, y: y + 10, id: 2 }] })
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await settle()
    check(!beforePinch.equals(await touchCanvas.screenshot()), 'El gesto de dos dedos no cambia la cámara')
    check(await mobile.locator('.plant-detail h3').innerText() === beforeTouch, 'El gesto de dos dedos selecciona parcelas')
  } finally {
    await mobileContext.close()
  }
  check(errors.length === 0, 'Excepciones JavaScript: ' + errors.join('; '))
  return { result: 'PASS', camera: 'zoom, persistence, rotate, pan, presets, limits, keyboard, pick vs drag, reduced motion, touch rotation and pinch', data: 'week, samples, flowers, zero, filters', responsive: [1440, 1366, 1024, 768, 390, 320], javascriptErrors: errors }
}
