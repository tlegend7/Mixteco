// Playwright CLI: run-code --filename tests/browser-viewer.js against the local app.
async (page) => {
  const check=(value,message)=>{if(!value) throw new Error(message)}
  const errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.context().route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//,route=>route.abort())
  await page.setViewportSize({width:1440,height:900})
  await page.reload({waitUntil:'domcontentloaded'})
  await page.getByRole('button',{name:'Pantalla completa',exact:true}).waitFor()
  check(await page.locator('.scene-failure').count()===0,'No inició WebGL')
  const source=await (await page.request.get(new URL('data/biometria.json',page.url()).href)).json()
  check(source.weeks.length===13 && source.records.length===52 && source.observations.length===416,'Datos incompletos')
  const logo=page.getByRole('img',{name:'Universidad Tecnológica de Panamá',exact:true})
  check(await logo.evaluate(img=>img.complete && img.naturalWidth>0),'No cargó el logo oficial')
  const header=await page.locator('.study-strip').boundingBox()
  check(header.y+header.height<100,'El logo agrandó el encabezado')
  await page.getByRole('checkbox',{name:'Rojo',exact:true}).uncheck()
  await page.getByRole('button',{name:'Sarán azul',exact:true}).click()
  await page.waitForTimeout(750)
  await page.getByRole('button',{name:'Ocultar cubiertas',exact:true}).click()
  await page.getByRole('button',{name:'Acercar a planta',exact:true}).click()
  await page.waitForTimeout(200)
  check((await page.locator('.point-focus').innerText()).includes('Planta ilustrativa'),'No se enfoca la planta')
  const zoom=()=>page.locator('.scene-scale').textContent().then(text=>Number(text.match(/Zoom ([\d.]+)/)[1]))
  check(await zoom()>3.2,'No supera el límite anterior')
  const canvas=page.locator('canvas')
  await page.screenshot({path:'output/playwright/viewer-close-plant.png',fullPage:true})
  await page.getByRole('button',{name:'Liberar cámara',exact:true}).click()
  check(await page.getByRole('checkbox',{name:'Rojo',exact:true}).isChecked()===false,'Liberar cámara cambió filtros')
  check((await page.locator('.plant-detail h3').innerText()).includes('azul'),'Liberar cámara borró selección analítica')
  await page.waitForTimeout(150)
  await canvas.screenshot({path:'output/playwright/viewer-before-fullscreen.png'})
  const cameraState=()=>page.locator('.field-wrap').evaluate(el=>el.__vueParentComponent.exposed.getCameraState())
  const originalCamera=await cameraState()
  await page.getByRole('button',{name:'Pantalla completa',exact:true}).click()
  await page.waitForFunction(()=>document.fullscreenElement===document.querySelector('.scene-panel'))
  check(await page.locator('#week-range').count()===1 && await page.locator('#timeline-title').count()===1,'Controles temporales duplicados')
  const full=await page.locator('.scene-panel').boundingBox()
  check(full.x===0 && full.y===0 && full.width===1440 && full.height===900,'No ocupa la pantalla')
  check(await page.locator('.scene-panel .timeline').evaluate(el=>getComputedStyle(el).position)==='absolute','La barra temporal no flota')
  await page.screenshot({path:'output/playwright/viewer-fullscreen-close.png'})
  const expandedZoom=await zoom()
  check(expandedZoom>3.2,'Se perdió el zoom al expandir')
  await page.keyboard.press('Escape')
  await page.waitForFunction(()=>!document.fullscreenElement && !document.querySelector('.scene-panel').classList.contains('is-expanded'))
  check(await zoom()===expandedZoom,'Escape reinició el zoom')
  check(await page.getByRole('slider').inputValue()==='13','Escape cambió la semana')
  check(await page.getByRole('checkbox',{name:'Rojo',exact:true}).isChecked()===false,'Escape cambió filtros')
  await page.waitForTimeout(200)
  const returnedCamera=await cameraState()
  await canvas.screenshot({path:'output/playwright/viewer-after-fullscreen.png'})
  check(JSON.stringify(originalCamera)===JSON.stringify(returnedCamera),'Se alteró el estado ortográfico de cámara: '+JSON.stringify({originalCamera,returnedCamera}))
  await page.getByRole('combobox',{name:'Enfocar estructura',exact:true}).selectOption('flowers')
  check((await page.locator('.point-focus').textContent()).includes('Flor ilustrativa'),'No se enfoca la flor')
  await page.screenshot({path:'output/playwright/viewer-flower.png',fullPage:true})
  const flowerBox=await canvas.boundingBox()
  await page.mouse.dblclick(flowerBox.x+flowerBox.width/2,flowerBox.y+flowerBox.height/2)
  await page.waitForTimeout(100)
  check((await page.locator('.point-focus').textContent()).includes('representación ilustrativa'),'Raycasting no enfoca una estructura')
  await page.getByRole('combobox',{name:'Enfocar estructura',exact:true}).selectOption('fruits')
  check((await page.locator('.point-focus').textContent()).includes('Fruto ilustrativo'),'No se enfoca el fruto')
  await page.screenshot({path:'output/playwright/viewer-fruit.png',fullPage:true})
  await page.getByRole('button',{name:'Pantalla completa',exact:true}).click()
  await page.getByRole('slider').focus()
  await page.keyboard.press('Home')
  check(await page.getByRole('slider').inputValue()==='1','No selecciona semana 1 en fullscreen')
  for(let i=0;i<12;i++) await page.keyboard.press('ArrowRight')
  check(await page.getByRole('slider').inputValue()==='13','No accede a las trece semanas')
  const beforeWeek=await zoom()
  await page.keyboard.press('ArrowLeft')
  check(await zoom()===beforeWeek,'La semana reinició el zoom')
  await page.getByRole('button',{name:'Reproducir evolución',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('#week-range').value==='13')
  check(await page.getByRole('button',{name:'Reproducir evolución',exact:true}).isVisible(),'No se detiene reproducción')
  await page.getByRole('button',{name:'Reiniciar evolución',exact:true}).click()
  check(await page.getByRole('slider').inputValue()==='1','No reinicia en fullscreen')
  await page.getByRole('button',{name:'Salir de pantalla completa',exact:true}).click()
  await page.waitForFunction(()=>!document.fullscreenElement)
  await page.getByRole('slider').focus()
  await page.keyboard.press('End')
  await page.getByRole('button',{name:'Centrar todo',exact:true}).click()
  await page.waitForTimeout(750)
  check(await zoom()===1,'Centrar todo no recupera escala')
  await page.getByRole('button',{name:'Acercar escenario',exact:true}).click({clickCount:32})
  await page.waitForTimeout(100)
  check((await cameraState()).zoom===40,'No se limita el zoom cercano a 40×')
  await page.getByRole('button',{name:'Centrar todo',exact:true}).click()
  await page.waitForTimeout(750)
  await page.locator('.field-canvas').focus()
  await page.keyboard.press('ArrowRight')
  await page.locator('.field-canvas').evaluate(el=>{
    for(let i=0;i<300;i++) el.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',code:'ArrowRight',bubbles:true}))
    for(let i=0;i<300;i++) el.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowUp',code:'ArrowUp',bubbles:true}))
  })
  await page.waitForTimeout(200)
  const bounded=await cameraState()
  check(Math.abs(bounded.target[0])<=7.65 && bounded.target[1]>=.25 && bounded.target[1]<=2.85 && Math.abs(bounded.target[2])<=2.9,'La cámara abandona el área del experimento')
  check(bounded.position[1]>bounded.target[1],'Cámara bajo el suelo o invertida')
  check(JSON.stringify(bounded.fieldPosition)==='[0,0,0]' && JSON.stringify(bounded.fieldScale)==='[1,1,1]','Se movió el modelo para simular navegación')
  await page.getByRole('button',{name:'Centrar todo',exact:true}).click()
  await page.waitForTimeout(750)
  await page.screenshot({path:'output/playwright/viewer-general.png',fullPage:true})
  for(const [width,height] of [[1920,1080],[1366,768],[1280,720],[1024,768],[768,1024],[390,844],[320,640]]) {
    await page.setViewportSize({width,height})
    await page.waitForTimeout(100)
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Desbordamiento normal a '+width)
    await page.getByRole('button',{name:'Pantalla completa',exact:true}).click()
    await page.waitForFunction(()=>!!document.fullscreenElement)
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Desbordamiento ampliado a '+width)
    const timeline=await page.locator('.timeline').boundingBox()
    check(timeline.x>=0 && timeline.y+timeline.height<=height,'Barra flotante fuera de pantalla a '+width)
    const active=await page.locator('.week-buttons button[aria-pressed=true]').boundingBox()
    check(active.x>=timeline.x && active.x+active.width<=timeline.x+timeline.width+1,'Semana activa oculta a '+width)
    if(width===390 || width===320) await page.screenshot({path:'output/playwright/viewer-fullscreen-'+width+'.png'})
    await page.getByRole('button',{name:'Salir de pantalla completa',exact:true}).click()
    await page.waitForFunction(()=>!document.fullscreenElement)
  }
  for (const mode of ['unavailable','rejected']) {
    const fallback=await page.context().browser().newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
    try {
    await fallback.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//,route=>route.abort())
    await fallback.addInitScript(mode=>{
      Object.defineProperty(document,'fullscreenEnabled',{value:mode!=='unavailable'})
      if(mode==='rejected') Element.prototype.requestFullscreen=()=>Promise.reject(new Error('Permission denied'))
    },mode)
    const mobile=await fallback.newPage()
    mobile.on('pageerror',e=>errors.push(e.message))
    await mobile.goto(page.url(),{waitUntil:'domcontentloaded'})
    await mobile.getByRole('button',{name:'Pantalla completa',exact:true}).tap()
    check(await mobile.locator('.scene-panel.is-expanded').count()===1,'No hay alternativa a Fullscreen API')
    check(/ampli/i.test(await mobile.getByRole('status').first().textContent()),'No se informa la alternativa')
    await mobile.getByRole('slider').focus()
    await mobile.keyboard.press('Tab')
    check(await mobile.evaluate(()=>document.querySelector('.scene-panel').contains(document.activeElement)),'El foco escapa del visor')
    await mobile.keyboard.press('Escape')
    check(await mobile.locator('.scene-panel.is-expanded').count()===0,'Escape no sale del modo alternativo')
    } finally { await fallback.close() }
  }
  check(errors.length===0,errors.join('; '))
  return {result:'PASS',nativeFullscreen:true,fallback:true,sharedTimeline:true,nearZoom:true,dataIntact:true,javascriptErrors:errors}
}
